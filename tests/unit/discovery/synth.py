def package(name: str, elements: str, indent: str = "  ") -> str:
    return (
        f"{HEADER}{indent}<AR-PACKAGES>\n{indent * 2}<AR-PACKAGE>\n"
        f"{indent * 3}<SHORT-NAME>{name}</SHORT-NAME>\n{indent * 3}<ELEMENTS>\n"
        f"{elements}{indent * 3}</ELEMENTS>\n{indent * 2}</AR-PACKAGE>\n"
        f"{indent}</AR-PACKAGES>\n</AUTOSAR>\n"
    )


def port(kind: str, name: str, interface: str, uuid: str) -> str:
    ref = "PROVIDED-INTERFACE-TREF" if kind == "P" else "REQUIRED-INTERFACE-TREF"
    return (
        f'          <{kind}-PORT-PROTOTYPE UUID="{uuid}">\n'
        f"            <SHORT-NAME>{name}</SHORT-NAME>\n"
        f'            <{ref} DEST="SENDER-RECEIVER-INTERFACE">/PortInterfaces/{interface}</{ref}>\n'
        f"          </{kind}-PORT-PROTOTYPE>\n"
    )


