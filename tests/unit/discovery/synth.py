def write(root: Path, rel: str, content: str | bytes) -> Path:
    path = root.joinpath(*rel.split("/"))
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_bytes(content.encode("utf-8"))
    return path


def build_repo(root: Path) -> Path:
    """Write the synthetic repo below ``root`` and return ``root``."""
    root.mkdir(parents=True, exist_ok=True)
    for rel, content in FILES.items():
        write(root, rel, content)
    return root


def git(repo: Path, *args: str) -> str:
    done = subprocess.run(  # noqa: S603 - fixed argument list in a test helper
        ["git", "-c", "user.name=Test", "-c", "user.email=test@example.invalid",
         "-c", "core.autocrlf=false", "-c", "commit.gpgsign=false", *args],
        cwd=repo, check=True, capture_output=True, text=True,
    )  # fmt: skip
    return done.stdout.strip()


def git_init(repo: Path, branch: str = "main") -> str:
    """Make ``repo`` a git repo with one commit; return the commit hash."""
    git(repo, "init", "-q", "-b", branch)
    return commit_all(repo, "initial")


def commit_all(repo: Path, message: str) -> str:
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", message, "--allow-empty")
    return git(repo, "rev-parse", "HEAD")


